/// Return (sine, cosine) in Q1.15 for a 16-bit full-turn electrical angle.
///
/// Matches M1_Trig_Functions in FOC_MC_MATH_clarkpark.c. The top ten
/// angle bits select the quadrant and table entry without interpolation.
#[inline]
pub fn sin_cos_q15_lut(angle: u16) -> (i16, i16) {
    let index = (angle >> 6) as u8;
    let direct = SIN_QUARTER_Q15[usize::from(index)];
    let reflected = SIN_QUARTER_Q15[usize::from(u8::MAX - index)];
    match angle >> 14 {
        0 => (direct, reflected),
        1 => (reflected, -direct),
        2 => (-direct, -reflected),
        _ => (-reflected, direct),
    }
}
